import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { feature } from 'topojson-client';

const WORLD_TOPO_URL = 'https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json';
const DOT_SPACING = 1.5;
const radians = degrees => degrees * Math.PI / 180;
const round = value => Number(value.toFixed(5));
const wrapLongitude = lon => ((lon + 180) % 360 + 360) % 360 - 180;

function pointInRing(lon, lat, { coordinates: ring, centerLon, minLat, maxLat }) {
  if (lat < minLat || lat > maxLat) return false;
  // Test the longitude copy nearest this ring's unwrapped coordinates.
  lon += 360 * Math.round((centerLon - lon) / 360);
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function prepareRing(ring) {
  const coordinates = [ring[0]];
  for (let i = 1; i < ring.length; i++) {
    const previous = coordinates.at(-1);
    coordinates.push([previous[0] + wrapLongitude(ring[i][0] - ring[i - 1][0]), ring[i][1]]);
  }
  const first = coordinates[0];
  const last = coordinates.at(-1);
  if (Math.abs(last[0] - first[0]) > 180) {
    // Antarctica's coastline winds around the pole without a synthetic pole
    // edge in the source. Close its sampling polygon through the polar cap.
    const pole = ring.reduce((sum, point) => sum + point[1], 0) < 0 ? -90 : 90;
    coordinates.push([last[0], pole], [first[0], pole], first);
  }
  const longitudes = coordinates.map(point => point[0]);
  const latitudes = coordinates.map(point => point[1]);
  return {
    coordinates,
    centerLon: (Math.min(...longitudes) + Math.max(...longitudes)) / 2,
    minLat: Math.min(...latitudes), maxLat: Math.max(...latitudes),
  };
}

const preparePolygons = polygons => polygons.map(rings => rings.map(prepareRing));
function pointOnPreparedLand(lat, lon, polygons) {
  return polygons.some(rings => pointInRing(lon, lat, rings[0]) &&
    !rings.slice(1).some(hole => pointInRing(lon, lat, hole)));
}

/** GeoJSON rings after the first ring are holes, including inland water. */
export function isPointOnLand(lat, lon, polygons) {
  return pointOnPreparedLand(lat, lon, preparePolygons(polygons));
}

export function buildGlobeGeometry(topology) {
  const land = feature(topology, topology.objects.land);
  const features = land.features || [land];
  const polygons = features.flatMap(({ geometry }) => {
    if (geometry.type === 'Polygon') return [geometry.coordinates];
    if (geometry.type === 'MultiPolygon') return geometry.coordinates;
    throw new Error(`Unsupported land geometry: ${geometry.type}`);
  });
  const dots = [];
  const samplingPolygons = preparePolygons(polygons);
  const rows = Math.ceil(178 / DOT_SPACING);
  for (let row = 0; row <= rows; row++) {
    const lat = Math.max(-89, 89 - row * DOT_SPACING);
    const lonStep = DOT_SPACING / Math.cos(radians(lat));
    const offset = row % 2 ? lonStep / 2 : 0;
    for (let lon = -180 + offset; lon < 180; lon += lonStep) {
      if (pointOnPreparedLand(lat, lon, samplingPolygons)) dots.push([round(lat), round(lon)]);
    }
  }
  return { dots };
}

async function generate() {
  const response = await fetch(WORLD_TOPO_URL);
  if (!response.ok) throw new Error(`Failed to fetch world topology: HTTP ${response.status}`);
  const { dots } = buildGlobeGeometry(await response.json());
  const output = resolve(dirname(fileURLToPath(import.meta.url)), '../lib/globe-land.generated.ts');
  const source = '// Generated by scripts/generate-globe-land.mjs. Do not edit manually.\n'
    + `// Source: ${WORLD_TOPO_URL}; 1.5-degree spherical dot spacing.\n`
    + 'export const GLOBE_LAND_COORDINATES: ReadonlyArray<readonly [number, number]> = '
    + `${JSON.stringify(dots)};\n`;
  await writeFile(output, source);
  console.log(`Generated ${dots.length} land dots at ${output}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await generate();
